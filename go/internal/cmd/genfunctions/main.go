// genfunctions inventories statically named server entry points. Run from go/.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	check := flag.Bool("check", false, "verify the checked-in inventory without writing")
	flag.Parse()
	fs := token.NewFileSet()
	files := map[string]*ast.File{}
	globals := map[string]bool{}
	paths, err := filepath.Glob("*.go")
	must(err)
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") || path == "redis_functions_manifest.go" {
			continue
		}
		file, err := parser.ParseFile(fs, path, nil, 0)
		must(err)
		files[path] = file
		for _, decl := range file.Decls {
			group, ok := decl.(*ast.GenDecl)
			if !ok || (group.Tok != token.CONST && group.Tok != token.VAR) {
				continue
			}
			for _, item := range group.Specs {
				value := item.(*ast.ValueSpec)
				for i, name := range value.Names {
					if i < len(value.Values) {
						globals[name.Name] = true
					}
				}
			}
		}
	}
	var stringExpression func(ast.Expr) bool
	stringExpression = func(e ast.Expr) bool {
		switch v := e.(type) {
		case *ast.BasicLit:
			return v.Kind == token.STRING
		case *ast.BinaryExpr:
			return v.Op == token.ADD && stringExpression(v.X) && stringExpression(v.Y)
		case *ast.ParenExpr:
			return stringExpression(v.X)
		case *ast.Ident:
			if globals[v.Name] {
				return true
			}
		}
		return false
	}
	entries := map[string]bool{`"return 1"`: true}
	// Read-only bodies are registered with flags={'no-writes'} and invoked with
	// FCALL_RO. A raw redisFunctionName caller hard-codes FCALL, so read-only
	// bodies must be invoked only through newReadOnlyRedisFunction.
	readOnly := map[string]bool{`"return 1"`: true}
	writable := map[string]bool{}
	named := map[string]bool{}

	for path, file := range files {
		ast.Inspect(file, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) != 1 {
				return true
			}
			fn, ok := call.Fun.(*ast.Ident)
			if !ok || (fn.Name != "redisFunctionName" && fn.Name != "newRedisFunction" && fn.Name != "newReadOnlyRedisFunction") || !stringExpression(call.Args[0]) {
				return true
			}
			var source bytes.Buffer
			must(format.Node(&source, fs, call.Args[0]))
			body := source.String()
			entries[body] = true
			switch {
			case fn.Name == "newReadOnlyRedisFunction":
				readOnly[body] = true
			case fn.Name == "newRedisFunction":
				writable[body] = true
			case path != "redis_functions.go":
				named[body] = true
			}
			return true
		})
	}
	for body := range readOnly {
		if writable[body] {
			panic("Redis function " + body + " is declared both read-only and writable")
		}
		if named[body] {
			panic("read-only Redis function " + body + " is invoked through redisFunctionName; use newReadOnlyRedisFunction so it runs with FCALL_RO")
		}
	}
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by go generate; DO NOT EDIT.\n\npackage redis\n\nvar redisFunctionBodies = []string{")
	for _, name := range sortedKeys(entries) {
		fmt.Fprintf(&output, "%s,\n", name)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output, "\n// Registered with flags={'no-writes'} and invoked with FCALL_RO.\nvar redisReadOnlyFunctionBodies = []string{")
	for _, name := range sortedKeys(readOnly) {
		fmt.Fprintf(&output, "%s,\n", name)
	}
	fmt.Fprintln(&output, "}")
	formatted, err := format.Source(output.Bytes())
	must(err)
	if *check {
		existing, err := os.ReadFile("redis_functions_manifest.go")
		must(err)
		if !bytes.Equal(existing, formatted) {
			panic("Redis function inventory is stale; run go generate .")
		}
		return
	}
	must(os.WriteFile("redis_functions_manifest.go", formatted, 0644))
}
func sortedKeys(set map[string]bool) []string {
	keys := make([]string, 0, len(set))
	for key := range set {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
